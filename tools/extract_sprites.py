#!/usr/bin/env python3
"""Regenerate assets/sprites.txt from Chromium's 1x offline sprite sheet.

The 1x sheet (assets/chromium/100-offline-sprite.png, BSD-3-Clause, see
assets/chromium/LICENSE) is dumped as plain pixel bitmaps, one char per pixel.
The game downsamples them to Braille dots at whatever scale fits the terminal
(src/sprites.rs), so the data here stays full fidelity.

Run from the repo root:  python3 tools/extract_sprites.py
Needs Pillow.
"""

from PIL import Image

SHEET = "assets/chromium/100-offline-sprite.png"
OUT = "assets/sprites.txt"

# name, x, y, w, h, dark_only, thin
# Positions are the ldpi entries in offline_sprite_definitions.ts plus the
# frame offsets from trex.ts / obstacle.ts / night_mode.ts / game_over_panel.ts.
# dark_only: only the dark grey (#535353) pixels count; the cloud, moon and
# stars are light grey, so for those any opaque pixel counts.
# thin: a dot lights if any of its pixels is set (keeps single-pixel lines and
# outlines); otherwise it needs half its pixels (suits the 2x2 pixel art).
TREX = 848
SPRITES = [
    ("trex_stand", TREX + 0, 2, 44, 47, True, False),
    ("trex_blink", TREX + 44, 2, 44, 47, True, False),
    ("trex_run1", TREX + 88, 2, 44, 47, True, False),
    ("trex_run2", TREX + 132, 2, 44, 47, True, False),
    ("trex_crash", TREX + 220, 2, 44, 47, True, False),
    ("trex_duck1", TREX + 264, 2, 59, 47, True, False),
    ("trex_duck2", TREX + 323, 2, 59, 47, True, False),
    # obstacle.ts: sourceX = (w * size) * (0.5 * (size - 1)) + spritePos.x
    ("cactus_small1", 228, 2, 17, 35, True, False),
    ("cactus_small2", 228 + 17, 2, 34, 35, True, False),
    ("cactus_small3", 228 + 51, 2, 51, 35, True, False),
    ("cactus_large1", 332, 2, 25, 50, True, False),
    ("cactus_large2", 332 + 25, 2, 50, 50, True, False),
    ("cactus_large3", 332 + 75, 2, 75, 50, True, False),
    ("ptero1", 134, 2, 46, 40, True, False),
    ("ptero2", 134 + 46, 2, 46, 40, True, False),
    ("cloud", 86, 2, 46, 14, False, True),
    ("horizon_flat", 2, 54, 600, 12, True, True),
    ("horizon_bumpy", 2 + 600, 54, 600, 12, True, True),
    ("star1", 645, 2, 9, 9, False, True),
    ("star2", 645, 2 + 9, 9, 9, False, True),
]
# night_mode.ts PHASES; phase 3 (offset 60) is the full moon, twice as wide.
for i, off in enumerate([140, 120, 100, 60, 40, 20, 0]):
    SPRITES.append((f"moon{i}", 484 + off, 2, 40 if i == 3 else 20, 40, False, True))
# The restart button (game_over_panel.ts) is drawn from text cells instead:
# as a sprite its arrow is a 3 px white cut-out that turns to mush past
# scale 2.


def main():
    im = Image.open(SHEET).convert("RGBA")

    def on(x, y, dark_only):
        r, g, b, a = im.getpixel((x, y))
        if a < 128:
            return False
        return r + g + b < 600 if dark_only else True

    out = [
        "# Generated by tools/extract_sprites.py from Chromium's 1x offline sprite",
        "# sheet (BSD-3-Clause, assets/chromium/LICENSE). One char per pixel.",
        "# Header: sprite <name> <thin 0|1>",
    ]
    for name, x, y, w, h, dark_only, thin in SPRITES:
        rows = ["".join("#" if on(x + i, y + j, dark_only) else "." for i in range(w)) for j in range(h)]
        out.append(f"sprite {name} {int(thin)}")
        out.extend(rows)
        if name == "cloud":
            # the blocks look's solid cloud: each row filled between its
            # outermost outline pixels (the outline is open at the bottom
            # left, so a flood fill would leak; every row is one span)
            out.append("sprite cloud_filled 0")
            for row in rows:
                a, b = row.find("#"), row.rfind("#")
                out.append(row if a < 0 else "." * a + "#" * (b - a + 1) + "." * (w - b - 1))
    with open(OUT, "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {OUT}: {len(SPRITES)} sprites")


if __name__ == "__main__":
    main()
